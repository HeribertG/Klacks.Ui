/**
 * Regenerates src/app/layer-dependencies-pending-owner-decision.constants.ts from the current import graph.
 * By default it only SHRINKS the list: entries that no longer violate are dropped, new disputed file/layer pairs are
 * reported and make the script fail instead of being added. `--rebuild` writes the full current state and is reserved for an
 * explicit owner decision (e.g. after the layer rule itself changed).
 * Usage: npm run layers:allowlist [-- --rebuild]
 */
import { writeFileSync } from 'fs';
import { resolve } from 'path';
import { Layer, pendingDecisionMap, scanProductionSources } from '../src/app/layer-dependencies.testing';
import { PENDING_OWNER_DECISION } from '../src/app/layer-dependencies-pending-owner-decision.constants';

const APP_ROOT = resolve(__dirname, '../src/app');
const OUTPUT_FILE = resolve(APP_ROOT, 'layer-dependencies-pending-owner-decision.constants.ts');
const REBUILD_FLAG = '--rebuild';

const HEADER = `// Copyright (c) Heribert Gasparoli. SPDX-License-Identifier: AGPL-3.0-only

/**
 * Generated by tools/generate-layer-allowlist.ts - do not edit by hand except to delete entries.
 * Shrink-only allowlist of file/layer pairs that the table in .claude/rules/frontend-architecture.md (super-repo)
 * forbids but its prose ("Presentation -> Domain Services -> Infrastructure API-Services") arguably allows, frozen until the
 * owner decides which reading holds, plus the shared -> domain imports that the table allows but that keep domain and
 * shared in a cycle. Key: importing file under src/app; value: the disputed layers it imports.
 * layer-dependencies.guard.spec.ts fails on any new entry and on any entry that no longer violates.
 */
import type { Layer } from './layer-dependencies.testing';

export const PENDING_OWNER_DECISION: Readonly<Record<string, readonly Layer[]>> = {
`;

function render(map: Record<string, Layer[]>): string {
  const lines = Object.keys(map)
    .sort()
    .map((file) => `  '${file}': [${map[file].map((layer) => `'${layer}'`).join(', ')}],`);
  return HEADER + lines.join('\n') + (lines.length ? '\n' : '') + '};\n';
}

const current = pendingDecisionMap(scanProductionSources(APP_ROOT).edges);
const rebuild = process.argv.includes(REBUILD_FLAG);
const next: Record<string, Layer[]> = {};
const added: string[] = [];

for (const [file, layers] of Object.entries(current)) {
  const known = PENDING_OWNER_DECISION[file] ?? [];
  const kept = rebuild ? layers : layers.filter((layer) => known.includes(layer));
  added.push(...layers.filter((layer) => !known.includes(layer)).map((layer) => `${file} -> ${layer}`));
  if (kept.length) {
    next[file] = kept;
  }
}

writeFileSync(OUTPUT_FILE, render(next));
const total = Object.values(next).reduce((sum, layers) => sum + layers.length, 0);
console.log(`Wrote ${Object.keys(next).length} files / ${total} file/layer pairs to ${OUTPUT_FILE}`);

if (added.length && !rebuild) {
  console.error(`New disputed file/layer pairs were NOT added (route them through a domain service instead):\n${added.join('\n')}`);
  process.exit(1);
}
