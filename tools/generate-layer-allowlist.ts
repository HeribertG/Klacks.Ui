/**
 * Regenerates src/app/layer-dependencies-legacy-violations.constants.ts from the current import graph.
 * By default it only SHRINKS the list: entries that no longer violate are dropped, new violating file/layer pairs are
 * reported and make the script fail instead of being added. `--rebuild` writes the full current state and is reserved for an
 * explicit owner decision (e.g. after the layer rule itself changed).
 * Usage: npm run layers:allowlist [-- --rebuild]
 */
import { writeFileSync } from 'fs';
import { resolve } from 'path';
import { Layer, legacyViolationMap, scanProductionSources } from '../src/app/layer-dependencies.testing';
import { LEGACY_LAYER_VIOLATIONS } from '../src/app/layer-dependencies-legacy-violations.constants';

const APP_ROOT = resolve(__dirname, '../src/app');
const OUTPUT_FILE = resolve(APP_ROOT, 'layer-dependencies-legacy-violations.constants.ts');
const REBUILD_FLAG = '--rebuild';

const HEADER = `// Copyright (c) Heribert Gasparoli. SPDX-License-Identifier: AGPL-3.0-only

/**
 * Generated by tools/generate-layer-allowlist.ts - do not edit by hand except to delete entries.
 * Shrink-only list of legacy file/layer pairs that .claude/rules/frontend-architecture.md (super-repo) forbids but that
 * already existed when the layer guard was introduced: presentation -> infrastructure, the remaining domain/services and
 * application edges to shared or to infrastructure folders other than api/storage/signalr, and the domain <-> shared
 * cycle. Imports of infrastructure/api, storage and signalr from domain/services and application are allowed by the
 * owner decision of 2026-10-20 and never listed. Key: importing file under src/app; value: the violated target layers.
 * layer-dependencies.guard.spec.ts fails on any new entry and on any entry that no longer violates.
 */
import type { Layer } from './layer-dependencies.testing';

export const LEGACY_LAYER_VIOLATIONS: Readonly<Record<string, readonly Layer[]>> = {
`;

function render(map: Record<string, Layer[]>): string {
  const lines = Object.keys(map)
    .sort()
    .map((file) => `  '${file}': [${map[file].map((layer) => `'${layer}'`).join(', ')}],`);
  return HEADER + lines.join('\n') + (lines.length ? '\n' : '') + '};\n';
}

const current = legacyViolationMap(scanProductionSources(APP_ROOT).edges);
const rebuild = process.argv.includes(REBUILD_FLAG);
const next: Record<string, Layer[]> = {};
const added: string[] = [];

for (const [file, layers] of Object.entries(current)) {
  const known = LEGACY_LAYER_VIOLATIONS[file] ?? [];
  const kept = rebuild ? layers : layers.filter((layer) => known.includes(layer));
  added.push(...layers.filter((layer) => !known.includes(layer)).map((layer) => `${file} -> ${layer}`));
  if (kept.length) {
    next[file] = kept;
  }
}

writeFileSync(OUTPUT_FILE, render(next));
const total = Object.values(next).reduce((sum, layers) => sum + layers.length, 0);
console.log(`Wrote ${Object.keys(next).length} files / ${total} file/layer pairs to ${OUTPUT_FILE}`);

if (added.length && !rebuild) {
  console.error(`New violating file/layer pairs were NOT added (route them through a domain service instead):\n${added.join('\n')}`);
  process.exit(1);
}
